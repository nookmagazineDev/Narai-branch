// ผู้ใช้ที่ล็อกอินไว้ + การจำกัดสาขา — ใช้ร่วมกันระหว่าง schedule.js กับ stock.js
//
// แยกออกมาเพื่อให้กติกาสาขามีที่มาที่เดียว ถ้าปล่อยให้แต่ละไฟล์เขียนเอง
// วันหนึ่งจะแก้ที่หนึ่งแล้วลืมอีกที่ ซึ่งเป็นกติกาเรื่องสิทธิ์ ไม่ควรมีสองฉบับ

const str = (v) => (v === null || v === undefined ? '' : String(v).trim());

/* ---------------------------- ผู้ใช้ที่ล็อกอินไว้ ----------------------------
   ไม่มีการล็อกอินซ้อนอีกชั้นที่นี่ — ใช้ user เดิมที่ล็อกอินเข้าระบบมาตั้งแต่แรก
   ฝั่งเว็บแนบมาให้ในฟิลด์ _user อัตโนมัติทุกคำสั่ง (ดู src/services/api.js)

   ข้อจำกัดที่ต้องรู้: _user มาจาก localStorage ของเบราว์เซอร์ ผู้ใช้แก้เองได้
   จึงกันได้แค่การกดผิดสาขาโดยไม่ตั้งใจ ไม่ใช่การกันคนที่ตั้งใจปลอม
   ถ้าต้องการกันจริงต้องให้ตอน login ออก token ที่เซ็นชื่อไว้แล้วตรวจที่นี่
   (ตอนนี้ Apps Script เดิมก็เชื่อสาขาที่ฝั่งเว็บส่งมาแบบเดียวกัน)
------------------------------------------------------------------------- */
export function sessionOf(body) {
  const u = body && typeof body._user === 'object' ? body._user : null;
  const username = str(u?.username);
  if (!username) return null;
  const branch = str(u?.branch);
  // name = ชื่อที่แสดง (hr_user.display_name) เอาไว้เขียนลงช่อง "ผู้อนุมัติ" ให้คนอ่านรู้ว่าใครกด
  // บัญชีที่ย้ายมาจากชีทยังไม่มีชื่อนี้ ฝั่งที่ใช้ต้องถอยไปใช้ username เสมอ
  const name = str(u?.name);
  return { username, name, branch, isAll: branch.toLowerCase() === 'all' };
}

/* ------------------------- สาขาที่เป็นตัวเดียวกัน -------------------------
   บางสาขามีรหัสสองแบบที่หมายถึงร้านเดียวกัน เพราะแต่ละระบบตั้งชื่อไว้ไม่ตรงกัน
   ตัวอย่างที่มีจริง: เว็บล็อกอินด้วย zjp แต่ชีท/POS/เครื่องสแกนนิ้วเขียนว่า SJP
   (ทั้งคู่คือ outlet 7 — ดู branchMap ใน server.js ที่แมป sjp กับ zjp ไปเลข 7 เหมือนกัน)

   ผลตอนยังไม่จับคู่กัน: ล็อกอินสาขาหนึ่งแล้วรายชื่อพนักงานกับประวัติสแกนนิ้วไม่ขึ้นเลย
   เพราะข้อมูลถูกเก็บไว้ใต้รหัสอีกตัว ทั้งที่เป็นร้านเดียวกัน

   กติกา:
     อ่าน  -> อ่านทุกรหัสในกลุ่ม (ข้อมูลเก่าที่ลงไว้ด้วยรหัสไหนก็เห็นหมด)
     เขียน -> ใช้รหัสที่หน้าเว็บส่งมาตามเดิม ไม่แปลง
              (ห้ามแปลงตอนเขียน ไม่งั้นข้อมูลเก่าที่ลงด้วยอีกรหัสจะกลายเป็นของกำพร้า)
     สิทธิ์ -> ถือว่าเป็นสาขาเดียวกัน เข้าถึงข้ามกันได้

   เพิ่มคู่ใหม่ที่นี่ที่เดียว แล้วทุกฝั่งได้ผลพร้อมกัน
--------------------------------------------------------------------------- */
const BRANCH_ALIAS_GROUPS = [
  ['zjp', 'sjp'],
];

/**
 * รหัสสาขาทั้งหมดที่ถือว่าเป็นร้านเดียวกันกับรหัสที่ให้มา (ตัวพิมพ์เล็ก)
 * ไม่อยู่ในกลุ่มไหน = คืนตัวมันเองตัวเดียว
 */
export function branchGroup(code) {
  const b = str(code).toLowerCase();
  if (!b) return [];
  const hit = BRANCH_ALIAS_GROUPS.find((g) => g.includes(b));
  return hit ? [...hit] : [b];
}

/* ------------------- คนที่สังกัดหลายสาขา (ช่องสาขามีหลายรหัส) -------------------
   ชีท DATA กรอกช่องสาขาของบางคนเป็นหลายรหัสคั่นด้วยจุลภาค เช่น 'SUM, IPR'
   (ผู้จัดการที่ดูแลสองร้าน) ค่านั้นเดินทางมาถึงที่นี่ตรงๆ เพราะหน้าเว็บส่ง
   "สาขาของพนักงาน" มากับแถวกะที่บันทึก

   ถ้าเทียบแบบตรงตัว 'sum, ipr' จะไม่เท่ากับ 'sum' -> ตอบ 403
   "ไม่มีสิทธิ์ดูข้อมูลของสาขา SUM, IPR" แล้วการบันทึกตารางทั้งสัปดาห์ล้มทั้งชุด
   เพราะคนคนเดียวในนั้นสังกัดสองสาขา (เคสจริงของสาขา sum)

   จึงแตกเป็นรายรหัสก่อนเทียบเสมอ และตอนเขียนให้ยึด "รหัสเดียว" ไม่เก็บทั้งพวง
--------------------------------------------------------------------------- */

/** แตกช่องสาขาเป็นรายรหัส — 'SUM, IPR' -> ['sum', 'ipr'] (คั่นด้วย , / | ; หรือช่องว่าง) */
export function branchCodes(value) {
  return str(value)
    .toLowerCase()
    .split(/[,\/|;+&]+|\s+/)
    .map((c) => c.trim())
    .filter(Boolean);
}

/** รหัสแรกของช่องสาขา — ใช้เป็น "สาขาหลัก" ตอนต้องเก็บลงฐานข้อมูลช่องเดียว */
export function primaryBranch(value) {
  return branchCodes(value)[0] || '';
}

/** สองค่านี้ชี้ถึงร้านเดียวกันไหม (รับค่าที่มีหลายรหัสได้ทั้งสองฝั่ง) */
export function sameBranch(a, b) {
  const xs = branchCodes(a);
  const ys = branchCodes(b);
  if (xs.length === 0 || ys.length === 0) return false;
  return xs.some((x) => branchGroup(x).some((code) => ys.includes(code)));
}

/**
 * สาขาที่คำสั่งนี้ทำงานด้วยได้จริง
 * user สิทธิ์ all เลือกสาขาไหนก็ได้ นอกนั้นถูกล็อกไว้ที่สาขาตัวเองเสมอ
 * (หน้าเว็บล็อกไว้อยู่แล้ว ตรงนี้กันซ้ำอีกชั้นเผื่อเรียก API ตรงๆ)
 */
export function branchFor(session, requested) {
  const want = str(requested);
  // คนที่สังกัดหลายสาขาส่งมาเป็นพวง ('SUM, IPR') — เก็บลงฐานข้อมูลได้ทีละรหัสเท่านั้น
  // จึงยึดรหัสแรกเป็นสาขาหลัก ('all' ไม่ใช่รหัสสาขาจริง ผ่านตัวนี้แล้วยังเป็น 'all' เหมือนเดิม)
  const primary = primaryBranch(want) || want;
  if (!session) return primary;
  if (session.isAll) return primary;
  // sameBranch() ครอบคลุมรหัสที่เป็นร้านเดียวกัน (เช่น zjp กับ sjp) จึงข้ามกันได้
  // และแตกพวงหลายรหัสให้แล้ว คนที่สังกัด 'SUM, IPR' จึงผ่านด่านนี้เมื่อล็อกอินด้วยสาขาใดสาขาหนึ่งในนั้น
  if (want && !sameBranch(want, session.branch)) {
    throw Object.assign(new Error(`ไม่มีสิทธิ์ดูข้อมูลของสาขา ${want}`), { forbidden: true });
  }
  // ผ่านด่านสิทธิ์แล้วยังคืน "รหัสที่ล็อกอิน" เสมอ ไม่ใช่รหัสพี่น้องที่ขอมา
  // เพื่อให้ข้อมูลที่บันทึกใหม่ลงใต้รหัสเดียวตลอด ไม่แตกเป็นสองกองเพิ่มอีก
  // (ฝั่งอ่านครอบทั้งกลุ่มอยู่แล้ว ของเก่าที่ลงด้วยอีกรหัสจึงยังเห็นครบ)
  return primaryBranch(session.branch) || session.branch;
}
