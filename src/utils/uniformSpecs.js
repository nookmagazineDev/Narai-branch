// รูปสเปคของยูนิฟอร์ม (ปุ่ม "ดูรายละเอียด" ในกล่องยูนิฟอร์ม หน้ารายชื่อพนักงาน)
//
// รูปเก็บที่ public/uniform/ ตั้งชื่อไฟล์ตามรหัสไอเทม เช่น public/uniform/80000018.jpg
// รหัสที่ใช้รูปเดียวกัน (ไอเทมเดียวกันคนละไซซ์) ให้ชี้ไปที่ไฟล์เดียว ไม่ต้องคัดลอกรูปซ้ำ
//
// เพิ่มรูปใหม่: วางไฟล์ใน public/uniform/ แล้วเพิ่มรหัสทั้งหมดที่ใช้รูปนั้นในตารางนี้
// รหัสที่ไม่อยู่ในตาราง = ปุ่มเป็นสีเทา "ไม่มีรูป"
const SPEC_IMAGES = {
  // เสื้อเชิ้ตหญิง แขนสามส่วน ผ้าค้อม 4534 สีดำ (สเปค PJ Garment 01/09/2568)
  '80000018.jpg': ['80000018', '80000019', '80000020', '80000021'],
  // เสื้อเชิ้ตชาย แขนยาว ผ้าค้อม 4534 สีดำ (สเปค PJ Garment 01/09/2568)
  '80000022.jpg': ['80000022', '80000023', '80000024', '80000025'],
};

/** รหัสเดียวกับ normCode() ฝั่งเซิร์ฟเวอร์ — ตัด .0 ท้าย + 0 นำหน้า + ตัวพิมพ์เล็ก */
const norm = (v) => String(v ?? '').trim().replace(/\.0+$/, '').replace(/^0+/, '').toLowerCase();

const BY_CODE = new Map();
for (const [file, codes] of Object.entries(SPEC_IMAGES)) {
  for (const code of codes) BY_CODE.set(norm(code), `/uniform/${file}`);
}

/** URL รูปสเปคของรหัสนี้ หรือ '' ถ้ายังไม่มีรูป */
export function uniformSpecImage(code) {
  return BY_CODE.get(norm(code)) || '';
}
